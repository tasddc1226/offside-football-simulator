// Writes apps/mobile/src/ui/avatarImageSources.ts: the layer atlas as base64 for the app's JS compositor (avatarCompose.ts).
// T-11-276 Metro asset requires resolve to Android drawable resources in release builds, which JS cannot read as bytes,
// so the PNG ships inside the bundle instead.
import { readdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../../', import.meta.url);
const dir = new URL('packages/game/assets/avatar-layers/', root);
const names = (await readdir(dir)).filter((f) => f.endsWith('.png')).sort();
if (names.length !== 1 || names[0] !== 'stand.png')
  throw new Error(`expected only stand.png, found ${names.join(', ')}`);
const b64 = (await readFile(new URL('stand.png', dir))).toString('base64');
const out = new URL('apps/mobile/src/ui/avatarImageSources.ts', root);
await writeFile(
  out,
  `// Generated by tooling/avatar-layers/mobile-sources.mjs from packages/game/assets/avatar-layers/stand.png. Do not edit.\n` +
    `export const avatarAtlasBase64 =\n  '${b64}';\n`,
);
console.log(`stand.png → ${b64.length} base64 chars`);
