// Writes apps/mobile/src/ui/avatarImageSources.ts: Metro needs a static require per layer atlas PNG.
import { readdir, writeFile } from 'node:fs/promises';
import { format, resolveConfig } from 'prettier';

const root = new URL('../../', import.meta.url);
const names = (await readdir(new URL('packages/game/assets/avatar-layers/', root)))
  .filter((f) => f.endsWith('.png'))
  .map((f) => f.slice(0, -4))
  .sort();
const out = new URL('apps/mobile/src/ui/avatarImageSources.ts', root);
const src = `/* eslint-disable @typescript-eslint/no-require-imports -- Metro requires static PNG asset references. */
// Generated by tooling/avatar-layers/mobile-sources.mjs. Static requires bundle every layer atlas.
const sources: Record<string, number> = {
${names.map((n) => `  '${n}': require('../../../../packages/game/assets/avatar-layers/${n}.png') as number,`).join('\n')}
};
export const avatarImageSource = (name: string): number => sources[name]!;
`;
await writeFile(out, await format(src, { ...(await resolveConfig(out)), filepath: out.pathname }));
console.log(`${names.length} atlases`);
