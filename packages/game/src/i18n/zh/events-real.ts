// realevents.ts 의 CAMP 와 같은 조건에서 같은 개수의 후보 중 pick 한 번 — 한국어와 같은 난수를 같은 만큼 쓴다.
const camp = (s: GameState): string =>
  s.leagueId === 'mls'
    ? pick(['美國佛羅里達', '美國亞利桑那', '墨西哥坎昆'])
    : s.leagueId === 'bra'
      ? pick(['美國佛羅里達', '巴西阿蒂巴亞'])
      : leagueOf(s.leagueId).tier <= 3
        ? pick(['土耳其安塔利亞', '泰國清邁', '日本鹿兒島', '濟州西歸浦'])
        : pick(['西班牙馬貝拉', '阿聯杜拜', '美國佛羅里達']);

// releaseEvent(아시안게임·올림픽 차출 협상)의 공통 문구 틀.
function release(o: {
  title: string;
  text: string;
  mil: string;
  rest: string;
  blessing: string;
  refusal: string;
  missed: string;
}): EventText {
  return {
    title: o.title,
    text: (s) => (isKorean(s) ? [o.text, o.mil, o.rest] : [o.text, o.rest]).join(''),
    choices: [
      {
        label: '直接找俱樂部高層談判',
        ok: o.blessing,
        fail: o.refusal,
      },
      {
        label: '以延長合約換取放人',
        ok: '以薪資不變、合約延長一年為條件，俱樂部同意放人。',
        fail: o.missed,
      },
      {
        label: '留在球隊專心打賽季',
        ok: '總教練很感謝你的決定。',
      },
    ],
  };
}

