// realevents.ts 의 CAMP 와 같은 조건에서 같은 개수의 후보 중 pick 한 번 — 한국어와 같은 난수를 같은 만큼 쓴다.
const camp = (s: GameState): string =>
  s.leagueId === 'mls'
    ? pick(['アメリカ・フロリダ', 'アメリカ・アリゾナ', 'メキシコ・カンクン'])
    : leagueOf(s.leagueId).tier <= 3
      ? pick(['トルコ・アンタルヤ', 'タイ・チェンマイ', '日本・鹿児島', '済州・西帰浦'])
      : pick(['スペイン・マルベーリャ', 'UAE・ドバイ', 'アメリカ・フロリダ']);

// releaseEvent(아시안게임·올림픽 차출 협상)의 공통 문구 틀.
function release(o: {
  title: string;
  text: string;
  mil: string;
  rest: string;
  blessing: string;
  refusal: string;
  missed: string;
}): EventText {
  return {
    title: o.title,
    text: (s) => (isKorean(s) ? [o.text, o.mil, o.rest] : [o.text, o.rest]).join(''),
    choices: [
      {
        label: 'クラブ首脳と直談判する',
        ok: o.blessing,
        fail: o.refusal,
      },
      {
        label: '契約延長と引き換えに招集を認めてもらう',
        ok: '年俸据え置きで契約を1年延長する条件で、招集が認められた。',
        fail: o.missed,
      },
      {
        label: 'チームに残ってシーズンに集中する',
        ok: '監督があなたの決断に感謝している。',
      },
    ],
  };
}

