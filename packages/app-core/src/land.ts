const ABC = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
/** 글자 코드 → 6비트 값(없으면 255). */
const SIX = new Uint8Array(128).fill(255);
for (let i = 0; i < ABC.length; i++) SIX[ABC.charCodeAt(i)] = i;
let bits: Uint8Array | null = null;
/** 처음 쓸 때 한 번만 푼다(웹·앱 어디서나 같은 결과 — atob에 기대지 않는다). */
function decode(): Uint8Array {
  const out = new Uint8Array((COLS * ROWS) / 8);
  let acc = 0,
    n = 0,
    j = 0;
  for (let i = 0; i < B64.length; i++) {
    const v = SIX[B64.charCodeAt(i)] ?? 255;
    if (v === 255) continue;
    acc = (acc << 6) | v;
    n += 6;
    if (n >= 8) {
      n -= 8;
      out[j++] = (acc >> n) & 0xff;
    }
  }
  return out;
}

/** 그 위경도가 육지 칸인지. 경도는 360도 밖이어도 감아서 본다(날짜변경선을 넘는 지도). */
export function landAt(lat: number, lon: number): boolean {
  const r = Math.floor((TOP - lat) / LAND_RES);
  if (r < 0 || r >= ROWS) return false;
  const c = ((Math.floor((lon + 180) / LAND_RES) % COLS) + COLS) % COLS;
  const i = r * COLS + c;
  bits ??= decode();
  return ((bits[i >> 3]! >> (i & 7)) & 1) === 1;
}
